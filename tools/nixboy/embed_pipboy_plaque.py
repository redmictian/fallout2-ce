"""Convert the generated nameplate to a small embedded game-palette texture.

Requires Pillow for authoring only. The game has no image-library dependency.
Run from any directory: python tools/nixboy/embed_pipboy_plaque.py [--check]
"""

from __future__ import annotations

import argparse
import io
from pathlib import Path

from PIL import Image


ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / "assets" / "nixboy"
WIDTH = 92
HEIGHT = 22


def artifacts() -> dict[Path, bytes]:
    source = Image.open(ASSETS / "pipboy-plaque-source.png").convert("RGBA")
    # Ignore stray near-transparent generation pixels outside the plaque.
    bounds = source.getchannel("A").point(lambda value: 255 if value >= 16 else 0).getbbox()
    if bounds is None:
        raise ValueError("The plaque source has no visible pixels")
    plaque = source.crop(bounds).resize((WIDTH, HEIGHT), Image.Resampling.LANCZOS)
    png = io.BytesIO()
    plaque.save(png, format="PNG", optimize=True)

    # Packed alpha8/RGB555: the engine resolves RGB555 through _colorTable at
    # drawing time, so the embedded image works with the loaded game palette.
    pixels = []
    rgba = plaque.tobytes()
    for offset in range(0, len(rgba), 4):
        red, green, blue, alpha = rgba[offset : offset + 4]
        rgb = ((red >> 3) << 10) | ((green >> 3) << 5) | (blue >> 3)
        pixels.append((alpha << 15) | rgb)
    rows = [
        "    " + ", ".join(f"0x{pixel:06x}" for pixel in pixels[offset : offset + WIDTH]) + ","
        for offset in range(0, len(pixels), WIDTH)
    ]
    header = "\n".join(
        [
            "// Generated by tools/nixboy/embed_pipboy_plaque.py; do not edit.",
            "// Original generated artwork and prompt: assets/nixboy/README.md.",
            "#ifndef NIXBOY_PIPBOY_PLAQUE_H",
            "#define NIXBOY_PIPBOY_PLAQUE_H",
            "",
            "namespace fallout {",
            "",
            f"static constexpr int kNixboyPipboyPlaqueWidth = {WIDTH};",
            f"static constexpr int kNixboyPipboyPlaqueHeight = {HEIGHT};",
            "// Alpha in bits 15..22; RGB555 in bits 0..14.",
            "// clang-format off",
            "static constexpr unsigned int kNixboyPipboyPlaquePixels[] = {",
            *rows,
            "};",
            "// clang-format on",
            "",
            "} // namespace fallout",
            "",
            "#endif /* NIXBOY_PIPBOY_PLAQUE_H */",
            "",
        ]
    ).encode("utf-8")
    return {
        ASSETS / "pipboy-plaque.png": png.getvalue(),
        ROOT / "src" / "nixboy_pipboy_plaque.h": header,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify checked-in artifacts without writing")
    args = parser.parse_args()
    for path, content in artifacts().items():
        if args.check:
            actual = path.read_bytes() if path.is_file() else b""
            if path.suffix == ".h":
                actual = actual.replace(b"\r\n", b"\n")
            if actual != content:
                raise SystemExit(f"Out of date: {path.relative_to(ROOT)}")
        else:
            path.write_bytes(content)
        print(f"{'Verified' if args.check else 'Wrote'} {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
