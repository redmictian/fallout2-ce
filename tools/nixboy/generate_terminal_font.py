"""Rasterize the pinned OFL Departure Mono into the terminal's ASCII cells.

Pillow is an authoring dependency only. Run with --check to verify the header.
"""

import argparse
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[2]
FONT_DIR = ROOT / 'third_party' / 'departure-mono'


def generate():
    font = ImageFont.truetype(str(FONT_DIR / 'DepartureMono-Regular.otf'), 11)
    rows = []
    for codepoint in range(32, 127):
        glyph = Image.new('L', (8, 16))
        ImageDraw.Draw(glyph).text((0, 0), chr(codepoint), font=font, fill=255)
        bits = [sum((1 << x) for x in range(8) if glyph.getpixel((x, y)) >= 128)
                for y in range(16)]
        rows.append('    { ' + ', '.join(f'0x{value:02x}' for value in bits)
                    + f' }}, // U+{codepoint:04X}')
    return ('// clang-format off\n'
            '// Generated by tools/nixboy/generate_terminal_font.py.\n'
            '// Derived from Departure Mono, Copyright 2022-2024 Helena Zhang.\n'
            '// Font data remains SIL OFL1.1; see OFL.txt and README.nixboy.md.\n'
            '#ifndef FALLOUT_NIXBOY_ASCII_BITMAP_H_\n'
            '#define FALLOUT_NIXBOY_ASCII_BITMAP_H_\n\n'
            'namespace fallout {\nnamespace nixboy {\n\n'
            'static constexpr unsigned char kTerminalAsciiBitmap[95][16] = {\n'
            + '\n'.join(rows) + '\n};\n\n'
            '} // namespace nixboy\n} // namespace fallout\n\n#endif\n'
            '// clang-format on\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = FONT_DIR / 'nixboy_ascii_bitmap.h'
    content = generate()
    if args.check:
        if target.read_text(encoding='utf-8') != content:
            raise SystemExit('Terminal font bitmap is out of date')
    else:
        target.write_text(content, encoding='utf-8')
    print('Verified terminal font bitmap' if args.check else 'Generated terminal font bitmap')


if __name__ == '__main__':
    main()
